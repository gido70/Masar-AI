function analyze(q){
 q=q.trim();
 if(!q)return {title:"اكتب حاجتك أولًا",body:"يمكنك وصفها كما تتحدث عادة، ولا تحتاج لمعرفة اسم الأداة."};
 if(/محاضر|صوت|تفريغ|تسجيل/.test(q))return {title:"مسار صوت ومعرفة",body:"الهدف → اللغة والمدة → STT (Speech-to-Text — تحويل الكلام إلى نص) → مراجعة → تلخيص/استخراج → فحص الجودة → اكتمل المسار."};
 if(/موقع|منصة|ويب|تطبيق/.test(q))return {title:"مسار بناء رقمي",body:"نوع المنتج → المستخدمون → الوظائف → MVP → طريقة البناء → قاعدة البيانات/الدخول عند الحاجة → نموذج أولي → اختبار → اكتمل المسار."};
 if(/فيديو|أفاتار|دبلج/.test(q))return {title:"مسار فيديو",body:"نوع الفيديو → المصدر → اللغة والجودة والميزانية → Script → توليد/تحرير → صوت/ترجمة → فحص → تصدير → اكتمل المسار."};
 if(/بحث|دراس|مراجع|ورق/.test(q))return {title:"مسار بحث ومعرفة",body:"سؤال البحث → نوع المصادر → اكتشاف الدراسات → تقييمها → استخراج البيانات → تنظيم المراجع → تلخيص/تحليل → مراجعة الاستشهادات."};
 return {title:"طلب غير مصنف بعد — وهذا مقصود في التصميم",body:"لن نقول «لا توجد نتيجة». سيستخرج النظام الهدف، يسألك أسئلة قصيرة، يطابقه بأقرب مسار، ويعرض مسارًا مبدئيًا. كما يسجل الطلب كـ Search Gap — فجوة بحث — حتى يُراجع ويُضاف للدليل إن تكرر."};
}
